<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use Spatie\Permission\Models\Role;
use Spatie\Permission\Models\Permission;

class RolePermissionSeeder extends Seeder
{
    /**
     * Role definitions for PT Dharma Control Cable Indonesia.
     * Organizational hierarchy: Director -> Manager -> Supervisor -> Staff
     */
    public function run(): void
    {
        // Reset cached roles and permissions
        app()[\Spatie\Permission\PermissionRegistrar::class]->forgetCachedPermissions();

        // ── Custom Payroll Workflow Permissions ──────────────────────────
        $customPermissions = [
            'Approve:Payroll',
            'Check:Payroll',
            'Submit:Payroll',
            'Calculate:Payroll',
            'MarkPaid:Payroll',
        ];

        foreach ($customPermissions as $perm) {
            Permission::firstOrCreate(['name' => $perm, 'guard_name' => 'web']);
        }

        // ── Resource Permissions (auto-generated by Shield) ─────────────
        // These are created by Filament Shield when resources are discovered.
        // We reference them here; if they don't exist yet, we create them.
        $resources = [
            'Attendance', 'Branch', 'Company', 'Deduction', 'Designation',
            'Earning', 'EmployeeDesignation', 'LeaveRequest', 'Payroll',
            'Shift', 'TaxSetting', 'User',
        ];

        $methods = [
            'ViewAny', 'View', 'Create', 'Update', 'Delete',
            'DeleteAny', 'Restore', 'ForceDelete', 'ForceDeleteAny',
            'RestoreAny', 'Replicate', 'Reorder',
        ];

        foreach ($resources as $resource) {
            foreach ($methods as $method) {
                Permission::firstOrCreate(
                    ['name' => "{$method}:{$resource}", 'guard_name' => 'web']
                );
            }
        }

        // ── Role Definitions ────────────────────────────────────────────

        // Helper: all CRUD permissions for a resource
        $allPerms = fn(string $r) => collect($methods)->map(fn($m) => "{$m}:{$r}")->all();
        // Helper: view-only permissions for a resource
        $viewPerms = fn(string $r) => ["ViewAny:{$r}", "View:{$r}"];

        // ────────────────────────────────────────────────────────────────
        // 1. Super Admin — all permissions (handled by Shield gate:before)
        // ────────────────────────────────────────────────────────────────
        $superAdmin = Role::firstOrCreate(['name' => 'super_admin', 'guard_name' => 'web']);
        $superAdmin->syncPermissions(Permission::where('guard_name', 'web')->get());

        // ────────────────────────────────────────────────────────────────
        // 2. Director (Level 1) — full access to all modules + approve
        // ────────────────────────────────────────────────────────────────
        $director = Role::firstOrCreate(['name' => 'director', 'guard_name' => 'web']);
        $directorPerms = array_merge(
            array_merge(...array_map($viewPerms, $resources)),
            $allPerms('Payroll'),
            ['Approve:Payroll', 'Check:Payroll', 'Submit:Payroll', 'Calculate:Payroll', 'MarkPaid:Payroll'],
        );
        $director->syncPermissions(array_unique($directorPerms));

        // ────────────────────────────────────────────────────────────────
        // 3. HR Manager (Level 2) — payroll master + check + HR modules
        // ────────────────────────────────────────────────────────────────
        $hrManager = Role::firstOrCreate(['name' => 'hr_manager', 'guard_name' => 'web']);
        $hrManagerPerms = array_merge(
            // Payroll: full CRUD + check + submit + mark paid
            $allPerms('Payroll'),
            ['Check:Payroll', 'Submit:Payroll', 'Calculate:Payroll', 'MarkPaid:Payroll'],
            // Payroll Master config
            $allPerms('Designation'),
            $allPerms('Shift'),
            $allPerms('Earning'),
            $allPerms('Deduction'),
            $allPerms('TaxSetting'),
            $allPerms('EmployeeDesignation'),
            // HR modules
            $allPerms('Attendance'),
            $allPerms('LeaveRequest'),
            $allPerms('User'),
            // View company/branch
            $viewPerms('Company'),
            $viewPerms('Branch'),
        );
        $hrManager->syncPermissions(array_unique($hrManagerPerms));

        // ────────────────────────────────────────────────────────────────
        // 4. Finance Manager (Level 2) — payroll approve + finance
        // ────────────────────────────────────────────────────────────────
        $financeManager = Role::firstOrCreate(['name' => 'finance_manager', 'guard_name' => 'web']);
        $financeManagerPerms = array_merge(
            // Payroll: view + approve + mark paid
            $allPerms('Payroll'),
            ['Approve:Payroll', 'MarkPaid:Payroll'],
            // View payroll master (read-only config)
            $viewPerms('Designation'),
            $viewPerms('Earning'),
            $viewPerms('Deduction'),
            $viewPerms('TaxSetting'),
            $viewPerms('EmployeeDesignation'),
            // View HR modules
            $viewPerms('Attendance'),
            $viewPerms('LeaveRequest'),
            $viewPerms('User'),
            $viewPerms('Company'),
            $viewPerms('Branch'),
        );
        $financeManager->syncPermissions(array_unique($financeManagerPerms));

        // ────────────────────────────────────────────────────────────────
        // 5. Manager (Level 2) — department payroll view + submit
        // ────────────────────────────────────────────────────────────────
        $manager = Role::firstOrCreate(['name' => 'manager', 'guard_name' => 'web']);
        $managerPerms = array_merge(
            // Payroll: view only
            $viewPerms('Payroll'),
            // HR modules: view
            $viewPerms('Attendance'),
            $viewPerms('LeaveRequest'),
            $viewPerms('EmployeeDesignation'),
        );
        $manager->syncPermissions(array_unique($managerPerms));

        // ────────────────────────────────────────────────────────────────
        // 6. Supervisor (Level 3) — team view + submit
        // ────────────────────────────────────────────────────────────────
        $supervisor = Role::firstOrCreate(['name' => 'supervisor', 'guard_name' => 'web']);
        $supervisorPerms = array_merge(
            $viewPerms('Payroll'),
            $viewPerms('Attendance'),
            $viewPerms('LeaveRequest'),
        );
        $supervisor->syncPermissions(array_unique($supervisorPerms));

        // ────────────────────────────────────────────────────────────────
        // 7. HRD/HRGA & IT (Level 3) — payroll master config + IT
        // ────────────────────────────────────────────────────────────────
        $hrdIt = Role::firstOrCreate(['name' => 'hrd_it', 'guard_name' => 'web']);
        $hrdItPerms = array_merge(
            // Full CRUD on payroll master
            $allPerms('Designation'),
            $allPerms('Shift'),
            $allPerms('Earning'),
            $allPerms('Deduction'),
            $allPerms('TaxSetting'),
            $allPerms('EmployeeDesignation'),
            // Payroll: view + calculate
            $viewPerms('Payroll'),
            ['Calculate:Payroll', 'Submit:Payroll'],
            // Attendance & Leave: full CRUD
            $allPerms('Attendance'),
            $allPerms('LeaveRequest'),
            // Users: full CRUD
            $allPerms('User'),
            // View company/branch
            $viewPerms('Company'),
            $viewPerms('Branch'),
        );
        $hrdIt->syncPermissions(array_unique($hrdItPerms));

        // ────────────────────────────────────────────────────────────────
        // 8. Operator (Level 4) — payroll data entry + calculate
        // ────────────────────────────────────────────────────────────────
        $operator = Role::firstOrCreate(['name' => 'operator', 'guard_name' => 'web']);
        $operatorPerms = array_merge(
            // Payroll: CRUD + calculate (no submit — submit is HR's role)
            $allPerms('Payroll'),
            ['Calculate:Payroll'],
            // Attendance & Leave: CRUD
            $allPerms('Attendance'),
            $allPerms('LeaveRequest'),
            // View payroll master (read-only)
            $viewPerms('Shift'),
            $viewPerms('Designation'),
            $viewPerms('EmployeeDesignation'),
        );
        $operator->syncPermissions(array_unique($operatorPerms));

        // ────────────────────────────────────────────────────────────────
        // 9. General Staff (Level 5) — view attendance & leave only
        // ────────────────────────────────────────────────────────────────
        $generalStaff = Role::firstOrCreate(['name' => 'general_staff', 'guard_name' => 'web']);
        $generalStaffPerms = array_merge(
            $viewPerms('Attendance'),
            $viewPerms('LeaveRequest'),
        );
        $generalStaff->syncPermissions(array_unique($generalStaffPerms));

        // ────────────────────────────────────────────────────────────────
        // 10. Employee — mobile app access only, no admin panel
        // ────────────────────────────────────────────────────────────────
        Role::firstOrCreate(['name' => 'employee', 'guard_name' => 'web']);
        // No admin permissions — ESS access is handled via API/mobile app

        // ────────────────────────────────────────────────────────────────
        // Ensure panel_user role exists (required by Shield config)
        // ────────────────────────────────────────────────────────────────
        Role::firstOrCreate(['name' => 'panel_user', 'guard_name' => 'web']);
    }
}
